package com.bxb.sunduk_pay.util;

/**
 * Enumeration representing different user roles
 * within the Sunduk Pay application.
 */
public enum UserRoles {

    /**
     * Administrator for Sunduk Pay related operations.
     */
    SUNDUK_PAY_ADMIN,
    /**
     * Administrator for GlobalPot related operations.
     */
    GLOBALPOT_ADMIN,
    /**
     * Normal user with no special privileges.
     */
    NORMAL_USER
}
