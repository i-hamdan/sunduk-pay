package com.bxb.sunduk_pay.util;
/**
 * Enum representing the different authentication provider methods available in the application.
 */
public enum AuthProviderMethod {
    /**
     * Represents authentication via a local phone number.
     */
    LOCAL_PHONE,
    /**
     * Represents authentication via a local email address.
     */
    LOCAL_EMAIL,
    /**
     * Represents authentication via Google Oauth.
     */
    GOOGLE

}
